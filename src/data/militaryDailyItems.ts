/**
 * Helper to select the item of the day deterministically based on date
 */
export function getMilitaryItemForDate(date: Date = new Date()): MilitaryDailyItem {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  const index = Math.abs(dayOfYear) % MILITARY_DAILY_ITEMS.length;
  return MILITARY_DAILY_ITEMS[index];
}
